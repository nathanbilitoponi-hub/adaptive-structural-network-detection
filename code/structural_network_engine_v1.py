def local_mask_from_cell(cell, grid, half_window, P):
    ix, iy, iz = cell
    x0 = max(0, ix - half_window) / grid
    x1 = min(grid, ix + half_window + 1) / grid
    y0 = max(0, iy - half_window) / grid
    y1 = min(grid, iy + half_window + 1) / grid
    z0 = max(0, iz - half_window) / grid
