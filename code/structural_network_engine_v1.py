for i in range(len(P)):
    nb = inds[i, 1:]   # exclude self
    Q = P[nb] - P[i]
    C = np.cov(Q.T)

    # eigenvalues
    w = np.linalg.eigvalsh(C)
    w = np.sort(np.maximum(w, 1e-12))[::-1]  # descending

    # filament score: linear structures -> λ1 >> λ2, λ3
    filament_score = (w[0] - w[1]) / w[0]

    # density weight: closer neighbours => stronger local structure
    density_weight = 1.0 / (np.median(dists[i, 1:]) + 1e-8)

    scores[i] = filament_score * density_weight

    # build mutual-ish edges with distance cut
    for j_idx, j in enumerate(nb):
        dd = dists[i, j_idx + 1]
        if dd < 2.2 * global_nn_med:
            a, b = sorted((i, j))
            edges.add((a, b))

