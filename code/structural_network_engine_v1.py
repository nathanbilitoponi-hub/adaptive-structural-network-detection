# ------------------------------------------------
# LOOP OVER REDSHIFT BINS
# ------------------------------------------------
for i in range(len(z_edges) - 1):
    zmin, zmax = z_edges[i], z_edges[i+1]
    mask = (gal_z > zmin) & (gal_z <= zmax)
    pts = gal_xyz[mask]

    if len(pts) < N_per_bin:
        print(f"skip bin {zmin:.3f}-{zmax:.3f}: only {len(pts)} galaxies")
        continue

    idx = rng.choice(len(pts), N_per_bin, replace=False)
    pts = pts[idx]

    # normalizzazione 0..1
    mins = pts.min(axis=0)
    maxs = pts.max(axis=0)
    span = maxs - mins
    span[span == 0] = 1.0
    P = (pts - mins) / span

    # persistent homology
    res = ripser(P, maxdim=2)
