import numpy as np
import matplotlib.pyplot as plt
from scipy.spatial.distance import pdist

print("=== COSMIC DISTANCE SCALE TEST ===")

# subsample per velocità
N = min(500, len(gal_xyz))
idx = np.random.choice(len(gal_xyz), N, replace=False)
pts = gal_xyz[idx]

# ------------------------------------------------
# nearest neighbour distances
# ------------------------------------------------
from scipy.spatial import cKDTree
tree = cKDTree(pts)
d_nn, _ = tree.query(pts, k=2)
nn = d_nn[:, 1]

print("\nNearest-neighbour scale")
print("mean  :", float(np.mean(nn)))
print("median:", float(np.median(nn)))
print("p90   :", float(np.percentile(nn, 90)))
print("max   :", float(np.max(nn)))

# ------------------------------------------------
# all pair distances
# ------------------------------------------------
pair_d = pdist(pts)

# limiti utili
pair_d = pair_d[(pair_d > 1) & (pair_d < 250)]

# istogramma pair distances
bins = np.linspace(0, 250, 60)
hist, edges = np.histogram(pair_d, bins=bins)
centers = 0.5 * (edges[:-1] + edges[1:])

# smoothing semplice
kernel = np.array([1, 2, 3, 2, 1], dtype=float)
kernel /= kernel.sum()
smooth = np.convolve(hist, kernel, mode="same")

# cerca picchi locali
peaks = []
for i in range(2, len(smooth)-2):
    if smooth[i] > smooth[i-1] and smooth[i] > smooth[i+1]:
        peaks.append((centers[i], smooth[i]))

# ordina per altezza
peaks = sorted(peaks, key=lambda x: x[1], reverse=True)

print("\nTop distance peaks")
for p in peaks[:10]:
    print(f"scale ~ {p[0]:.1f}   strength = {p[1]:.1f}")

# cerca BAO-like window
bao_peaks = [p for p in peaks if 120 <= p[0] <= 180]
if len(bao_peaks) > 0:
    best_bao = max(bao_peaks, key=lambda x: x[1])
    print(f"\nPossible BAO-like peak near: {best_bao[0]:.1f}")
else:
    print("\nNo clear BAO-like peak in 120-180 range")

# ------------------------------------------------
# plots
# ------------------------------------------------
plt.figure(figsize=(12, 4))

plt.subplot(1, 2, 1)
plt.hist(nn, bins=25)
plt.xlabel("nearest-neighbour distance")
plt.ylabel("count")
plt.title("Nearest-neighbour scale")

plt.subplot(1, 2, 2)
plt.plot(centers, hist, alpha=0.4, label="raw")
plt.plot(centers, smooth, label="smoothed")
plt.axvspan(120, 180, alpha=0.15, label="BAO window")
plt.xlabel("pair distance")
plt.ylabel("count")
plt.title("Pair-distance spectrum")
plt.legend()

plt.tight_layout()
plt.show()

print("\nDONE.")

