def filament_strength(pts, rng=None, max_points=140):
    pts = np.asarray(pts, float)
    if len(pts) < min_points:
        return np.nan

    if len(pts) > max_points:
        if rng is None:
            rng = np.random.default_rng()
        idx = rng.choice(len(pts), max_points, replace=False)
        pts = pts[idx]

    res = ripser(pts, maxdim=1)
    h1 = res["dgms"][1]

    if len(h1) == 0:
        return 0.0

    pers = h1[:, 1] - h1[:, 0]
    pers = pers[np.isfinite(pers) & (pers > 0)]
    if len(pers) == 0:
        return 0.0

    return float(0.7 * np.mean(pers) + 0.3 * np.percentile(pers, 90))

