def make_branch(start, direction, length, npts, amp1=0.02, amp2=0.015, f1=4, f2=3, noise_scale=0.006):
    t = np.linspace(0, 1, npts)

    direction = np.asarray(direction, float)
    direction = direction / np.linalg.norm(direction)

    tmp = np.array([0.0, 0.0, 1.0])
    if abs(np.dot(tmp, direction)) > 0.9:
        tmp = np.array([0.0, 1.0, 0.0])

    e1 = np.cross(direction, tmp)
    e1 = e1 / np.linalg.norm(e1)
    e2 = np.cross(direction, e1)
    e2 = e2 / np.linalg.norm(e2)

    centerline = (
        np.asarray(start)[None, :]
        + (length * t)[:, None] * direction[None, :]
        + (amp1 * np.sin(f1 * np.pi * t))[:, None] * e1[None, :]
        + (amp2 * np.cos(f2 * np.pi * t))[:, None] * e2[None, :]
    )

    noise = rng.normal(scale=noise_scale, size=centerline.shape)
    return centerline + noise

