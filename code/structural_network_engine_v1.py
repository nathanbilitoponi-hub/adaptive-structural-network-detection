def prune_graph_to_backbone(adj, min_keep=8, n_iter=6):
    M = adj.copy().tocsr()
    active = np.arange(M.shape[0])

    for _ in range(n_iter):
        deg = np.diff(M.indptr)
        leaves = np.where(deg <= 1)[0]
        if len(active) <= min_keep or len(leaves) == 0:
            break

        rem = leaves[:max(1, len(leaves) // 2)]
        keep_mask = np.ones(len(active), dtype=bool)
        keep_mask[rem] = False

        if keep_mask.sum() < min_keep:
            break

