def path_length(P):
    if len(P) < 2:
        return 0.0
    return float(np.sum(np.linalg.norm(np.diff(P, axis=0), axis=1)))

def endpoint_distance(P):
    if len(P) < 2:
        return 0.0
    return float(np.linalg.norm(P[-1] - P[0]))

def straightness(P):
    L = path_length(P)
    if L <= 0:
        return 0.0
    return endpoint_distance(P) / L

def turning_angles(P):
    ang = []
    for i in range(1, len(P)-1):
        v1 = P[i] - P[i-1]
        v2 = P[i+1] - P[i]
        n1 = np.linalg.norm(v1)
        n2 = np.linalg.norm(v2)
        if n1 < 1e-12 or n2 < 1e-12:
            ang.append(np.pi)
            continue
        c = np.dot(v1, v2) / (n1 * n2)
        c = np.clip(c, -1.0, 1.0)
        ang.append(np.arccos(c))
    return np.array(ang)

def significance_test(P, runs=150):
    if len(P) < 2:
        return np.nan, np.nan, np.nan, np.nan
    vals = []
    mins = P.min(axis=0)
    maxs = P.max(axis=0)
    for _ in range(runs):
        R = rng.uniform(mins, maxs, size=P.shape)
        order = np.argsort(R[:, 0])
        R = R[order]
        vals.append(straightness(R))
    vals = np.asarray(vals, float)
    mu = float(np.mean(vals))
    sd = float(np.std(vals))
    if sd == 0:
        sd = 1e-9
    z = (straightness(P) - mu) / sd
    pct = 100.0 * np.mean(vals < straightness(P))
    return mu, sd, z, pct

def recover_path(pred, s, t):
    path = [t]
    cur = t
    while cur != s and cur != -9999:
        cur = pred[s, cur]
        if cur == -9999:
            return []
        path.append(cur)
    return path[::-1]

