    print(f"H1 count = {len(h1)}")
    print(f"H2 count = {len(h2)}")
    print(f"mean H1 persistence = {H1_pmean[-1]:.5f}")
    print(f"mean H2 persistence = {H2_pmean[-1]:.5f}")
