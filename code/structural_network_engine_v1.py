import numpy as np
import matplotlib.pyplot as plt
from scipy.spatial import cKDTree

print("=== 3D COSMIC WEB MAP ===")

# subsample per visualizzazione
N = min(600, len(gal_xyz))
idx = np.random.choice(len(gal_xyz), N, replace=False)
pts = gal_xyz[idx]

# normalizza solo per stabilità grafica
mins = pts.min(axis=0)
maxs = pts.max(axis=0)
span = maxs - mins
span[span == 0] = 1.0
P = (pts - mins) / span

tree = cKDTree(P)

# collega ogni punto ai k vicini più vicini entro una distanza massima
k = 4
r_link = 0.12

dists, inds = tree.query(P, k=k+1)

edges = set()
for i in range(len(P)):
    for j in range(1, k+1):
        nb = inds[i, j]
        dd = dists[i, j]
        if dd < r_link:
            a, b = sorted((i, nb))
            edges.add((a, b))

edges = list(edges)

print("points:", len(P))
print("edges :", len(edges))
print("k     :", k)
print("r_link:", r_link)

# degree
deg = np.zeros(len(P), dtype=int)
for a, b in edges:
    deg[a] += 1
    deg[b] += 1

print("mean degree:", float(np.mean(deg)))
print("max degree :", int(np.max(deg)))

# ------------------------------------------------
# plot 3D
# ------------------------------------------------
fig = plt.figure(figsize=(8, 7))
ax = fig.add_subplot(111, projection="3d")

# punti
ax.scatter(P[:, 0], P[:, 1], P[:, 2], s=5, alpha=0.7)

# filamenti
for a, b in edges:
    ax.plot(
        [P[a, 0], P[b, 0]],
        [P[a, 1], P[b, 1]],
        [P[a, 2], P[b, 2]],
        linewidth=0.5,
        alpha=0.5
    )

ax.set_title("3D Cosmic Web Filament Map")
ax.set_xlabel("x")
