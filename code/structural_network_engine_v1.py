def node_linearity_scores(pts, k=8):
    tree = cKDTree(pts)
    dists, inds = tree.query(pts, k=min(k+1, len(pts)))
    scores = np.zeros(len(pts))
    for i in range(len(pts)):
        nb = inds[i, 1:]
        if len(nb) < 3:
            scores[i] = 0.0
            continue
        Q = pts[nb] - pts[i]
        C = np.cov(Q.T)
        w = np.linalg.eigvalsh(C)
        w = np.sort(np.maximum(w, 1e-12))[::-1]
        scores[i] = float((w[0] - w[1]) / w[0])
    return scores

def longest_path_approx(pts):
    # cheap approximation: PCA order + smoothed path
    X = pts - pts.mean(axis=0)
    C = np.cov(X.T)
    w, v = np.linalg.eigh(C)
    axis = v[:, np.argmax(w)]
    t = X @ axis
    order = np.argsort(t)
    P = pts[order].copy()

    # light smoothing
    for _ in range(2):
        R = P.copy()
        for i in range(1, len(P)-1):
            R[i] = 0.25 * P[i-1] + 0.5 * P[i] + 0.25 * P[i+1]
        P = R
    return P

def significance_vs_random(segment, runs=250, rng=None):
    if rng is None:
        rng = np.random.default_rng()
    real_s = straightness(segment)
    mins = segment.min(axis=0)
    maxs = segment.max(axis=0)

    sims = []
    for _ in range(runs):
        R = rng.uniform(mins, maxs, size=segment.shape)
        # sort along x-like longest spread axis
        X = R - R.mean(axis=0)
        C = np.cov(X.T)
        w, v = np.linalg.eigh(C)
        axis = v[:, np.argmax(w)]
        order = np.argsort(X @ axis)
        R = R[order]
        sims.append(straightness(R))

    sims = np.asarray(sims, float)
    mu = float(np.mean(sims))
    sd = float(np.std(sims))
    if sd == 0:
        sd = 1e-9
    z = (real_s - mu) / sd
    pct = 100.0 * np.mean(sims < real_s)
    return real_s, mu, sd, z, pct

